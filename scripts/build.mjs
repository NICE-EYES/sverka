// Builds dist/index.html from src/web: one self-contained page
// (host it anywhere, e.g. GitHub Pages, or open it from disk).
import fs from 'node:fs';
import path from 'node:path';
import * as esbuild from 'esbuild';

const root = path.resolve('.');
const dist = path.join(root, 'dist');
fs.mkdirSync(dist, { recursive: true });

// Embedded example statements (invented data) for the first screen.
const b64 = (f) => fs.readFileSync(path.join(root, 'test/fixtures', f)).toString('base64');
fs.writeFileSync(
  path.join(root, 'src/web/samples.js'),
  `// Generated by scripts/build.mjs from test/fixtures — invented example statements.\n` +
    `export const SAMPLES = ${JSON.stringify({
      ru: { name: 'пример-выписка-апрель-2026.pdf', data: b64('ru_card.pdf') },
      en: { name: 'example-checking-march-2026.pdf', data: b64('us_checking.pdf') },
    })};\n`
);

const result = await esbuild.build({
  entryPoints: [path.join(root, 'src/web/app.js')],
  bundle: true,
  format: 'iife',
  target: ['es2020'],
  minify: true,
  write: false,
  legalComments: 'none',
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const template = fs.readFileSync(path.join(root, 'src/web/template.html'), 'utf8');
const fragment = template.replace('<!--APP-->', () => `<script>\n${js}\n</script>`);

const titleEnd = fragment.indexOf('</style>') + '</style>'.length;
const head = fragment.slice(0, titleEnd);
const body = fragment.slice(titleEnd);
const full = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
${head}
</head>
<body>
${body}
</body>
</html>
`;
fs.writeFileSync(path.join(dist, 'index.html'), full);
console.log('dist/index.html', (full.length / 1024).toFixed(1) + ' KB');
